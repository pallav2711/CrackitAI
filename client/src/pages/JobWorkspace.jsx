/* ── Resume Upload ──────────────────────────────────────────────────────── */
function ResumeTab({ job, onJobUpdate }) {
  const [uploading, setUploading] = useState(false);
  const fileRef = useRef(null);

  const handleFile = async (file) => {
    if (!file) return;
    const ext = file.name.split('.').pop().toLowerCase();
    if (!['pdf', 'doc', 'docx'].includes(ext)) {
      toast.error('Only PDF, DOC, DOCX supported'); return;
    }
    setUploading(true);
    const fd = new FormData();
    fd.append('resume', file);
    try {
      const { data } = await api.post(`/jobs/${job._id}/upload-resume`, fd, {
        headers: { 'Content-Type': 'multipart/form-data' },
        timeout: 90000,
      });
      onJobUpdate(data.data);
      toast.success('Resume uploaded and parsed!');
    } catch (err) {
      toast.error(err.response?.data?.message || 'Upload failed');
    } finally { setUploading(false); }
  };

  const hasResume = !!(job.resumeText || job.parsedResume?.name);

  return (
    <div className="space-y-6 max-w-2xl">
      <div
        className={`border-2 border-dashed p-12 text-center cursor-pointer transition-colors ${
          hasResume ? 'border-nb-black bg-nb-yellow/5' : 'border-nb-black/30 hover:border-nb-black hover:bg-nb-yellow/10'
        }`}
        style={{ borderRadius: '8px' }}
        onClick={() => fileRef.current?.click()}
        onDragOver={e => e.preventDefault()}
        onDrop={e => { e.preventDefault(); handleFile(e.dataTransfer.files[0]); }}
      >
        <input ref={fileRef} type="file" className="hidden" accept=".pdf,.doc,.docx"
          onChange={e => handleFile(e.target.files[0])} />
        {uploading ? (
          <>
            <Loader2 className="w-10 h-10 animate-spin mx-auto mb-3 text-nb-black/40" />
            <p className="font-black text-sm">Parsing resume with AI…</p>
            <p className="text-xs text-nb-black/40 mt-1">This may take 10–30 seconds</p>
          </>
        ) : (
          <>
            <Upload className={`w-10 h-10 mx-auto mb-3 ${hasResume ? 'text-nb-black/50' : 'text-nb-black/25'}`} />
            <p className="font-black text-sm uppercase tracking-wide">
              {hasResume ? 'Re-upload resume' : 'Drop resume here or click to upload'}
            </p>
            <p className="text-xs text-nb-black/40 mt-1">PDF, DOC, DOCX — max 5 MB</p>
          </>
        )}
      </div>

      {hasResume && (
        <div className="bg-white border-2 border-nb-black p-5 space-y-4" style={{ borderRadius: '8px', boxShadow: '3px 3px 0 #111' }}>
          <div className="flex items-center gap-2 border-b-2 border-nb-black/10 pb-3">
            <CheckCircle className="w-4 h-4 text-green-600" />
            <p className="font-black text-sm uppercase tracking-wide">Resume Parsed</p>
            {job.resumeFileName && <span className="text-xs text-nb-black/35 font-mono ml-auto">{job.resumeFileName}</span>}
          </div>
          <div className="grid sm:grid-cols-2 gap-3 text-sm">
            {job.parsedResume?.name && (
              <div><span className="nb-label">Name</span><p className="font-bold">{job.parsedResume.name}</p></div>
            )}
            {job.parsedResume?.email && (
              <div><span className="nb-label">Email</span><p className="font-bold">{job.parsedResume.email}</p></div>
            )}
            <div><span className="nb-label">Skills found</span><p className="font-bold text-lg">{job.parsedResume?.skills?.length || 0}</p></div>
            <div><span className="nb-label">Experience entries</span><p className="font-bold text-lg">{job.parsedResume?.experience?.length || 0}</p></div>
          </div>
          {job.parsedResume?.skills?.length > 0 && (
            <div>
              <span className="nb-label">Skills</span>
              <div className="flex flex-wrap gap-1.5 mt-2">
                {job.parsedResume.skills.slice(0, 25).map(s => (
                  <span key={s} className="text-[11px] font-bold px-2 py-0.5 bg-[#F5F1E8] border-2 border-nb-black/20" style={{ borderRadius: '3px' }}>{s}</span>
                ))}
                {job.parsedResume.skills.length > 25 && (
                  <span className="text-[11px] text-nb-black/40">+{job.parsedResume.skills.length - 25} more</span>
                )}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

/* ── ATS Score ──────────────────────────────────────────────────────────── */
function ATSTab({ job, onJobUpdate }) {
  const [loading, setLoading] = useState(false);

  const run = async () => {
    setLoading(true);
    try {
      const { data } = await api.post(`/jobs/${job._id}/ats-score`);
      onJobUpdate(data.data);
      toast.success('ATS score calculated!');
    } catch (err) {
      toast.error(err.response?.data?.message || 'ATS calculation failed');
    } finally { setLoading(false); }
  };

  const hasResume = !!(job.resumeText || job.parsedResume?.name);
  const hasScore  = job.atsScore != null;  // FIX: was `!job.atsScore` which broke on score=0

  if (!hasScore) return (
    <div className="max-w-md space-y-4">
      <p className="text-sm text-nb-black/60 leading-relaxed">
        Calculate how well your resume matches the job description. The AI performs semantic matching — not just keyword counting.
      </p>
      <ActionBtn onClick={run} loading={loading} disabled={!hasResume}>
        <Target className="w-4 h-4" /> Calculate ATS Score
      </ActionBtn>
      {!hasResume && (
        <div className="flex items-center gap-2 p-3 bg-amber-50 border-2 border-amber-300 text-xs font-bold text-amber-800" style={{ borderRadius: '6px' }}>
          <AlertCircle className="w-4 h-4 flex-shrink-0" />
          Go to the Resume tab and upload your resume first.
        </div>
      )}
    </div>
  );

  const breakdown = job.atsBreakdown || {};

  return (
    <div className="space-y-6 max-w-2xl">

      {/* Score hero */}
      <div className={`border-2 border-nb-black p-6 flex items-center gap-6 ${scoreBg(job.atsScore)}`} style={{ borderRadius: '8px', boxShadow: '4px 4px 0 #111' }}>
        <ScoreRing score={job.atsScore} label="ATS Match" size={100} />
        <div className="flex-1 space-y-2">
          <p className={`text-4xl font-black font-mono ${scoreColor(job.atsScore)}`}>{job.atsScore}<span className="text-xl">/100</span></p>
          <p className="text-sm font-bold text-nb-black/60">
            {job.atsScore >= 80 ? '✅ Strong match — good chances of passing ATS filters.'
             : job.atsScore >= 60 ? '⚠️ Moderate match — some gaps to address.'
             : job.atsScore >= 40 ? '⚠️ Weak match — significant improvements needed.'
             : '❌ Poor match — resume needs major rework for this role.'}
          </p>
          <ActionBtn onClick={run} loading={loading} variant="ghost">
            <RefreshCw className="w-3.5 h-3.5" /> Re-run
          </ActionBtn>
        </div>
      </div>

      {/* Score breakdown bars */}
      {Object.keys(breakdown).length > 0 && (
        <div className="bg-white border-2 border-nb-black p-5" style={{ borderRadius: '8px', boxShadow: '3px 3px 0 #111' }}>
          <p className="text-[11px] font-black uppercase tracking-widest mb-4">Score Breakdown</p>
          <div className="space-y-3.5">
            {Object.entries(breakdown).map(([k, v]) => {
              const barColor = v >= 80 ? 'bg-green-500' : v >= 60 ? 'bg-amber-400' : 'bg-red-500';
              return (
                <div key={k}>
                  <div className="flex justify-between text-xs font-bold mb-1.5">
                    <span className="uppercase tracking-wide text-nb-black/60">{k.replace(/([A-Z])/g, ' $1').trim()}</span>
                    <span className={`font-mono ${v >= 80 ? 'text-green-700' : v >= 60 ? 'text-amber-700' : 'text-red-600'}`}>{v}%</span>
                  </div>
                  <div className="h-2.5 border-2 border-nb-black bg-[#F5F1E8]">
                    <div className={`h-full ${barColor} border-r-2 border-nb-black transition-all duration-700`} style={{ width: `${Math.max(v, 0)}%` }} />
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* Strong matches / Missing skills */}
      <div className="grid sm:grid-cols-2 gap-4">
        {job.atsStrongMatches?.length > 0 && (
          <div className="bg-green-50 border-2 border-green-300 p-4" style={{ borderRadius: '6px', boxShadow: '3px 3px 0 #166534' }}>
            <p className="text-[10px] font-black uppercase tracking-widest text-green-800 mb-3">✓ Strong Matches ({job.atsStrongMatches.length})</p>
            <ul className="space-y-1.5">
              {job.atsStrongMatches.map((m, i) => (
                <li key={i} className="text-xs text-green-800 flex gap-1.5 items-start">
                  <CheckCircle className="w-3.5 h-3.5 flex-shrink-0 mt-0.5" />{m}
                </li>
              ))}
            </ul>
          </div>
        )}
        {job.atsMissingSkills?.length > 0 && (
          <div className="bg-red-50 border-2 border-red-300 p-4" style={{ borderRadius: '6px', boxShadow: '3px 3px 0 #991b1b' }}>
            <p className="text-[10px] font-black uppercase tracking-widest text-red-800 mb-3">✕ Missing Skills ({job.atsMissingSkills.length})</p>
            <ul className="space-y-1.5">
              {job.atsMissingSkills.map((m, i) => (
                <li key={i} className="text-xs text-red-800 flex gap-1.5 items-start">
                  <AlertCircle className="w-3.5 h-3.5 flex-shrink-0 mt-0.5" />{m}
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>

      {/* Weak matches */}
      {job.atsWeakMatches?.length > 0 && (
        <div className="bg-amber-50 border-2 border-amber-300 p-4" style={{ borderRadius: '6px' }}>
          <p className="text-[10px] font-black uppercase tracking-widest text-amber-800 mb-3">⚠ Weak Matches — Needs Strengthening</p>
          <div className="flex flex-wrap gap-2">
            {job.atsWeakMatches.map((m, i) => (
              <span key={i} className="text-xs font-bold px-2 py-1 bg-amber-100 text-amber-800 border border-amber-300" style={{ borderRadius: '3px' }}>{m}</span>
            ))}
          </div>
        </div>
      )}

      {/* Recommendations */}
      {job.atsRecommendations?.length > 0 && (
        <div className="bg-nb-yellow border-2 border-nb-black p-5" style={{ borderRadius: '6px', boxShadow: '3px 3px 0 #111' }}>
          <p className="text-[11px] font-black uppercase tracking-widest mb-3">Recommendations</p>
          <ul className="space-y-2">
            {job.atsRecommendations.map((r, i) => (
              <li key={i} className="text-sm flex gap-2 items-start">
                <span className="font-black flex-shrink-0 mt-0.5">→</span>{r}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

/* ── Skill Gap ──────────────────────────────────────────────────────────── */
function SkillsTab({ job, onJobUpdate }) {
  const [loading, setLoading] = useState(false);

  const run = async () => {
    setLoading(true);
    try {
      const { data } = await api.post(`/jobs/${job._id}/skill-gap`);
      onJobUpdate(data.data);
      toast.success('Skill gap analysed!');
    } catch (err) {
      toast.error(err.response?.data?.message || 'Skill gap analysis failed');
    } finally { setLoading(false); }
  };

  const importanceStyles = {
    critical: 'bg-red-100 text-red-800 border-red-300',
    high:     'bg-orange-100 text-orange-800 border-orange-300',
    medium:   'bg-amber-50 text-amber-800 border-amber-300',
    low:      'bg-gray-100 text-gray-600 border-gray-300',
  };

  // FIX: was `!gap?.missing && !gap?.have` which broke when arrays were present but empty
  // Now shows the analysis view whenever skillGap object exists at all
  const gap        = job.skillGap;
  const hasRun     = gap != null && typeof gap === 'object' && ('have' in gap || 'missing' in gap || 'improve' in gap || 'niceToHave' in gap);
  const hasResume  = !!(job.resumeText || job.parsedResume?.name);

  if (!hasRun) return (
    <div className="max-w-md space-y-4">
      <p className="text-sm text-nb-black/60 leading-relaxed">
        Compare your skills against the job requirements. The AI categorises each skill as something you have, need to improve, or are missing entirely.
      </p>
      <ActionBtn onClick={run} loading={loading} disabled={!hasResume}>
        <TrendingUp className="w-4 h-4" /> Analyse Skill Gap
      </ActionBtn>
      {!hasResume && (
        <div className="flex items-center gap-2 p-3 bg-amber-50 border-2 border-amber-300 text-xs font-bold text-amber-800" style={{ borderRadius: '6px' }}>
          <AlertCircle className="w-4 h-4 flex-shrink-0" />
          Upload your resume first (Resume tab).
        </div>
      )}
    </div>
  );

  const SkillSection = ({ title, bg, border, shadow, items, showWhy }) => {
    if (!items?.length) return null;
    return (
      <div className={`border-2 p-5 ${bg} ${border}`} style={{ borderRadius: '6px', boxShadow: shadow || '3px 3px 0 #111' }}>
        <p className="text-[11px] font-black uppercase tracking-widest mb-3">{title} ({items.length})</p>
        <div className="space-y-2.5">
          {items.map((item, i) => {
            const skill = typeof item === 'string' ? item : item.skill;
            const imp   = typeof item === 'string' ? null : item.importance;
            const why   = typeof item === 'string' ? null : item.why;
            return (
              <div key={i} className="flex items-start gap-2">
                {imp && (
                  <span className={`text-[9px] font-black px-1.5 py-0.5 border flex-shrink-0 mt-0.5 capitalize ${importanceStyles[imp] || importanceStyles.low}`} style={{ borderRadius: '2px' }}>
                    {imp}
                  </span>
                )}
                <div>
                  <span className="text-sm font-bold">{skill}</span>
                  {showWhy && why && <p className="text-xs text-nb-black/50 mt-0.5 leading-relaxed">{why}</p>}
                </div>
              </div>
            );
          })}
        </div>
      </div>
    );
  };

  const totalHave    = gap.have?.length    || 0;
  const totalMissing = gap.missing?.length || 0;
  const coverage     = totalHave + totalMissing > 0 ? Math.round((totalHave / (totalHave + totalMissing)) * 100) : 0;

  return (
    <div className="space-y-5 max-w-2xl">
      {/* Summary bar */}
      <div className="bg-white border-2 border-nb-black p-4 flex items-center gap-4" style={{ borderRadius: '8px', boxShadow: '3px 3px 0 #111' }}>
        <div className="flex-1">
          <div className="flex justify-between text-xs font-bold mb-1.5">
            <span className="uppercase tracking-wide text-nb-black/60">Skill Coverage</span>
            <span className="font-mono">{coverage}%</span>
          </div>
          <div className="h-3 border-2 border-nb-black bg-[#F5F1E8]">
            <div className={`h-full border-r-2 border-nb-black ${coverage >= 70 ? 'bg-green-500' : coverage >= 50 ? 'bg-amber-400' : 'bg-red-500'}`}
              style={{ width: `${coverage}%` }} />
          </div>
          <p className="text-[10px] text-nb-black/40 mt-1">{totalHave} matched · {totalMissing} missing · {gap.improve?.length || 0} to improve</p>
        </div>
        <ActionBtn onClick={run} loading={loading} variant="ghost">
          <RefreshCw className="w-3.5 h-3.5" /> Re-run
        </ActionBtn>
      </div>

      <SkillSection title="✓ Already Have"     bg="bg-green-50"   border="border-green-300"  shadow="3px 3px 0 #166534" items={gap.have}       showWhy={false} />
      <SkillSection title="⚠ Need to Improve"  bg="bg-amber-50"   border="border-amber-300"  shadow="3px 3px 0 #92400e" items={gap.improve}    showWhy={true} />
      <SkillSection title="✕ Missing"           bg="bg-red-50"     border="border-red-300"    shadow="3px 3px 0 #991b1b" items={gap.missing}    showWhy={true} />
      <SkillSection title="★ Nice to Have"      bg="bg-[#F5F1E8]" border="border-nb-black/20" shadow="3px 3px 0 #111"   items={gap.niceToHave} showWhy={false} />

      {!gap.have?.length && !gap.missing?.length && !gap.improve?.length && (
        <div className="p-4 bg-amber-50 border-2 border-amber-300 text-sm text-amber-800" style={{ borderRadius: '6px' }}>
          The AI couldn't extract enough skill data. Try re-running after ensuring the resume and JD were properly parsed.
        </div>
      )}
    </div>
  );
}

