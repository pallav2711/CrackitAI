/* ── Helpers ─────────────────────────────────────────────────────────────── */
const scoreColor = (s) =>
  s == null ? 'text-nb-black/30'
  : s >= 80  ? 'text-green-700'
  : s >= 60  ? 'text-amber-700'
  :             'text-red-700';

const scoreBg = (s) =>
  s == null ? ''
  : s >= 80  ? 'bg-green-50 border-green-300'
  : s >= 60  ? 'bg-amber-50 border-amber-300'
  :             'bg-red-50 border-red-300';

/* ── Download plain-text cover letter ──────────────────────────────────── */
const downloadTextFile = (text, filename) => {
  const blob = new Blob([text], { type: 'text/plain' });
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href     = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
};

/* ── Download tailored resume as PDF ───────────────────────────────────── */
const downloadTailoredResumePDF = async (text, jobTitle) => {
  // Import lazily to avoid loading @react-pdf/renderer until needed
  const { Document, Page, Text, View, StyleSheet, pdf: pdfRenderer } = await import('@react-pdf/renderer');

  const styles = StyleSheet.create({
    page:    { fontFamily: 'Helvetica', fontSize: 10, color: '#111', padding: 40, lineHeight: 1.5 },
    title:   { fontSize: 14, fontFamily: 'Helvetica-Bold', marginBottom: 16, letterSpacing: -0.3 },
    content: { fontSize: 10, lineHeight: 1.6, whiteSpace: 'pre-wrap' },
    footer:  { position: 'absolute', bottom: 20, left: 40, right: 40, textAlign: 'center', fontSize: 8, color: '#999', borderTopWidth: 0.5, borderTopColor: '#ddd', paddingTop: 6 },
  });

  const doc = (
    <Document title={`Tailored Resume — ${jobTitle || 'Resume'}`}>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>Tailored Resume — {jobTitle || 'Position'}</Text>
        <Text style={styles.content}>{text}</Text>
        <Text style={styles.footer} fixed>Generated by CrackIt AI · crackiitai.vercel.app</Text>
      </Page>
    </Document>
  );

  const blob = await pdfRenderer(doc).toBlob();
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href     = url;
  a.download = `Tailored_Resume_${(jobTitle || 'Job').replace(/\s+/g, '_')}.pdf`;
  a.click();
  URL.revokeObjectURL(url);
};

/* ── Score ring (SVG) ───────────────────────────────────────────────────── */
const ScoreRing = ({ score, label, size = 80 }) => {
  const r     = (size / 2) - 8;
  const circ  = 2 * Math.PI * r;
  const pct   = score != null ? Math.min(score, 100) / 100 : 0;
  const dash  = circ * pct;
  const color = score == null ? '#ddd'
    : score >= 80 ? '#1A7A4A'
    : score >= 60 ? '#D97706'
    : '#DC2626';
  return (
    <div className="flex flex-col items-center gap-1">
      <svg width={size} height={size} style={{ transform: 'rotate(-90deg)' }}>
        <circle cx={size/2} cy={size/2} r={r} fill="none" stroke="#e5e7eb" strokeWidth="6" />
        <circle cx={size/2} cy={size/2} r={r} fill="none" stroke={color} strokeWidth="6"
          strokeDasharray={`${dash} ${circ}`} strokeLinecap="round" />
        <text x="50%" y="50%" dominantBaseline="middle" textAnchor="middle"
          style={{ transform: 'rotate(90deg)', transformOrigin: '50% 50%',
            fontSize: size < 70 ? 13 : 17, fontWeight: 900, fill: color, fontFamily: 'var(--font-mono)' }}>
          {score != null ? score : '—'}
        </text>
      </svg>
      <span className="text-[10px] font-black uppercase tracking-widest text-nb-black/45">{label}</span>
    </div>
  );
};

const ActionBtn = ({ onClick, loading, disabled, children, variant = 'primary', className = '' }) => (
  <button
    onClick={onClick}
    disabled={loading || disabled}
    className={`btn ${variant === 'primary' ? 'btn-primary' : 'btn-ghost'} ${loading || disabled ? 'opacity-50 cursor-not-allowed' : ''} ${className}`}
  >
    {loading ? <Loader2 className="w-4 h-4 animate-spin" /> : children}
  </button>
);

const CopyBtn = ({ text }) => {
  const [copied, setCopied] = useState(false);
  const handle = () => {
    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      toast.success('Copied to clipboard!');
      setTimeout(() => setCopied(false), 2000);
    });
  };
  return (
    <button onClick={handle} className="btn btn-ghost btn-sm">
      {copied ? <><CheckCircle className="w-3.5 h-3.5" /> Copied!</> : <><Copy className="w-3.5 h-3.5" /> Copy</>}
    </button>
  );
};

